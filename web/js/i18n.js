const I18N = (() => {
  const listeners = new Set();
  let lang = 'uz';

  function t(key, vars) {
    const s = DICT[lang][key] ?? DICT.en[key] ?? key;
    return vars ? s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] === undefined ? '' : vars[k])) : s;
  }

  function setHtmlLang() { document.documentElement.lang = lang; }

  /** (Re)translate every element marked with data-i18n / data-i18n-placeholder. */
  function apply(root = document) {
    root.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.dataset.i18n); });
    root.querySelectorAll('[data-i18n-placeholder]').forEach((el) => { el.placeholder = t(el.dataset.i18nPlaceholder); });
    root.querySelectorAll('[data-i18n-title]').forEach((el) => { el.title = t(el.dataset.i18nTitle); });
    root.querySelectorAll('[data-i18n-aria]').forEach((el) => { el.setAttribute('aria-label', t(el.dataset.i18nAria)); });
    setHtmlLang();
  }

  function setLang(next) {
    if (!DICT[next]) return;
    lang = next;
    U.store.set('sng.lang', next);
    listeners.forEach((fn) => fn(next));
  }

  function init() {
    const saved = U.store.get('sng.lang');
    lang = DICT[saved] ? saved : 'uz'; // Uzbek is the default, whatever the browser language is
    apply();
  }

  return { t, apply, init, setLang, setHtmlLang, onChange: (fn) => listeners.add(fn), flatpickrLocale: () => ({ ru: 'ru', uz: 'uz_latn' }[lang] || 'default'), get lang() { return lang; } };
})();

window.I18N = I18N;
window.t = I18N.t;
